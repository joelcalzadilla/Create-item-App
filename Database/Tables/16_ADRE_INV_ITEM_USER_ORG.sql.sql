
  CREATE TABLE "ADRE_INV_ITEM_USER_ORG" 
   (	"USER_ORG_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"APP_USER_NAME" VARCHAR2(100), 
	"EBS_ORGANIZATION_ID" NUMBER NOT NULL ENABLE, 
	"DEFAULT_FLAG" VARCHAR2(1) DEFAULT 'N' NOT NULL ENABLE, 
	"PREFERRED_UOM_SYSTEM" VARCHAR2(20), 
	"ACTIVE_FLAG" VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"CREATION_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"LAST_UPDATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"LAST_UPDATE_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"LAST_UPDATE_LOGIN" VARCHAR2(100), 
	"RECORD_VERSION_NUMBER" NUMBER DEFAULT 1 NOT NULL ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C1" CHECK (ebs_organization_id > 0) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C2" CHECK (default_flag IN ('Y', 'N')) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C3" CHECK (active_flag IN ('Y', 'N')) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C4" CHECK (record_version_number > 0) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C5" CHECK (
        app_user_name IS NOT NULL OR default_flag = 'Y'
    ) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_C6" CHECK (
        (default_flag = 'Y'
         AND preferred_uom_system IS NOT NULL
         AND preferred_uom_system IN ('IMPERIAL', 'METRIC'))
        OR
        (default_flag = 'N' AND preferred_uom_system IS NULL)
    ) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_USER_ORG_PK" PRIMARY KEY ("USER_ORG_ID")
  USING INDEX  ENABLE
   ) ;

  CREATE INDEX "ADRE_INV_ITEM_USER_ORG_N1" ON "ADRE_INV_ITEM_USER_ORG" ("EBS_ORGANIZATION_ID", "ACTIVE_FLAG") 
  ;

   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."USER_ORG_ID" IS 'Surrogate identifier for the user and organization mapping.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."APP_USER_NAME" IS 'APEX APP_USER, normalized to uppercase; NULL identifies the global fallback row.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."EBS_ORGANIZATION_ID" IS 'Existing Oracle EBS inventory organization, validated by the package against MTL_PARAMETERS.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."DEFAULT_FLAG" IS 'Y for the user default or the fallback row; at most one active default per user.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."PREFERRED_UOM_SYSTEM" IS 'IMPERIAL or METRIC preference on the default row; item-type configuration resolves this preference to a specific UOM code.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."ACTIVE_FLAG" IS 'Y makes the mapping available for new requests.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_USER_ORG"."RECORD_VERSION_NUMBER" IS 'Incremented on update; callers must compare their previously read value for optimistic locking.';
   COMMENT ON TABLE "ADRE_INV_ITEM_USER_ORG"  IS 'Maps an APEX user to available EBS organizations. The active default row supplies a preferred UOM system; a NULL user name supplies the global fallback.';

  CREATE OR REPLACE EDITIONABLE TRIGGER "TRG_ADRE_INV_ITEM_USER_ORG" 
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_user_org
FOR EACH ROW
DECLARE
    l_user  VARCHAR2(100);
    l_login VARCHAR2(100);
BEGIN
    l_user := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    l_login := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER);
    :NEW.app_user_name := UPPER(TRIM(:NEW.app_user_name));
    :NEW.default_flag := UPPER(TRIM(:NEW.default_flag));
    :NEW.preferred_uom_system := UPPER(TRIM(:NEW.preferred_uom_system));
    :NEW.active_flag := UPPER(TRIM(:NEW.active_flag));
    IF INSERTING THEN
        :NEW.created_by := NVL(:NEW.created_by, l_user);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1);
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1;
    END IF;
    :NEW.last_updated_by := l_user;
    :NEW.last_update_date := SYSDATE;
    :NEW.last_update_login := l_login;
END;

/
ALTER TRIGGER "TRG_ADRE_INV_ITEM_USER_ORG" ENABLE;