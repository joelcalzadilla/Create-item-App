-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Automatically maintain audit information and normalize configurable
-- Item Attribute values for ADRE_INV_ITEM_ATTRIBUTE.
-- =====================================================================

CREATE OR REPLACE TRIGGER ops.adre_inv_item_attribute_biu
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_attribute
FOR EACH ROW

DECLARE

    l_user
        VARCHAR2(100);

    l_login
        VARCHAR2(100);

BEGIN

    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX user when available.
    --
    -- Use the current Oracle database user when the operation is
    -- executed outside Oracle APEX.
    -- =================================================================

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX session identifier when available.
    -- =================================================================

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the internal attribute code.
    --
    -- Example:
    -- lead_time_days
    --
    -- becomes:
    -- LEAD_TIME_DAYS
    -- =================================================================

    :NEW.attribute_code :=
        UPPER
        (
            TRIM
            (
                :NEW.attribute_code
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Remove unnecessary leading and trailing spaces from the
    -- user-facing attribute name.
    -- =================================================================

    :NEW.attribute_name :=
        TRIM
        (
            :NEW.attribute_name
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the configured data type.
    -- =================================================================

    :NEW.attribute_data_type :=
        UPPER
        (
            TRIM
            (
                :NEW.attribute_data_type
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the default Unit of Measure code when populated.
    -- =================================================================

    :NEW.unit_of_measure :=
        UPPER
        (
            TRIM
            (
                :NEW.unit_of_measure
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize required and active indicators.
    -- =================================================================

    :NEW.required_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.required_flag
            )
        );


    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Remove unnecessary leading and trailing spaces from Oracle EBS
    -- mapping information.
    -- =================================================================

    :NEW.ebs_attribute_name :=
        TRIM
        (
            :NEW.ebs_attribute_name
        );


    :NEW.ebs_attribute_group :=
        TRIM
        (
            :NEW.ebs_attribute_group
        );


    IF INSERTING THEN

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize creation audit information for a new attribute.
        -- =============================================================

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );


        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize the first row version.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );

    ELSE

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Preserve the original creation audit information.
        -- =============================================================

        :NEW.created_by :=
            :OLD.created_by;

        :NEW.creation_date :=
            :OLD.creation_date;


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Increment the row version number on every update.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;

    END IF;


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Refresh last-update audit information for inserts and updates.
    -- =================================================================

    :NEW.last_updated_by :=
        l_user;

    :NEW.last_update_date :=
        SYSDATE;

    :NEW.last_update_login :=
        l_login;

END;
/

