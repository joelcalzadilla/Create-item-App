-- Purpose:
-- Recreate the configurable Item Attribute definition table for the
-- final Adhesives Research Inventory Item Creation application.
--
-- This table defines the dynamic attributes that can appear inside the
-- Organization Details sections in Oracle APEX.
--
-- Examples include:
--   - Coater
--   - RLDH
--   - Coat Weight
--   - Width
--   - Length
--   - Lead Time Days
--   - Planning Method
--
-- ITEM_SECTION_ID identifies the Details section where the attribute
-- belongs.
--
-- ATTRIBUTE_DATA_TYPE determines how Oracle APEX renders and validates
-- the value.
--
-- Valid data types:
--   CHAR
--   NUMBER
--   DATE
--   YES_NO
--
-- EBS_ATTRIBUTE_NAME and EBS_ATTRIBUTE_GROUP provide configurable
-- mapping information for the Oracle EBS integration.
--
-- This table stores metadata only.
-- User-entered transactional values will be stored separately.
-- =====================================================================


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Drop the existing table when it already exists.
--
-- CASCADE CONSTRAINTS removes foreign key references from previously
-- created dependent application objects during the schema rebuild.
--
-- ORA-00942 is ignored because it means the table does not exist.
-- Any other Oracle error is raised normally.
-- =====================================================================

BEGIN
    EXECUTE IMMEDIATE
        'DROP TABLE ops.adre_inv_item_attribute CASCADE CONSTRAINTS PURGE';

EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/


