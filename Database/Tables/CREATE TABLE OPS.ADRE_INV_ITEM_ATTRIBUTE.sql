        NOT NULL,

    item_section_id
        NUMBER
        NOT NULL,

    attribute_code
        VARCHAR2(100)
        NOT NULL,

    attribute_name
        VARCHAR2(240)
        NOT NULL,

    attribute_data_type
        VARCHAR2(30)
        NOT NULL,

    description
        VARCHAR2(1000),

    default_value
        VARCHAR2(1000),

    unit_of_measure
        VARCHAR2(30),

    required_flag
        VARCHAR2(1)
        DEFAULT 'N'
        NOT NULL,

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    ebs_attribute_name
        VARCHAR2(240),

    ebs_attribute_group
        VARCHAR2(240),

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_attribute_pk
        PRIMARY KEY
        (
            item_attribute_id
        ),

    CONSTRAINT adre_inv_item_attribute_fk1
        FOREIGN KEY
        (
            item_section_id
        )
        REFERENCES ops.adre_inv_item_section
        (
            item_section_id
        ),

    CONSTRAINT adre_inv_item_attribute_u1
        UNIQUE
        (
            attribute_code
        ),

    CONSTRAINT adre_inv_item_attribute_ck1
        CHECK
        (
            attribute_data_type IN
            (
                'CHAR',
                'NUMBER',
                'DATE',
                'YES_NO'
            )
        ),

    CONSTRAINT adre_inv_item_attribute_ck2
        CHECK
        (
            required_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_attribute_ck3
        CHECK
        (
            active_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_attribute_ck4
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_attribute_ck5
        CHECK
        (
            record_version_number > 0
        )
);


