   COMMENT ON COLUMN "ADRE_INV_ITEM_ATTR_VALUE"."ITEM_ATTR_VALUE_ID" IS 'Surrogate primary key generated by Oracle for each transactional Item Attribute value.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_ATTR_VALUE"."REQUEST_ORG_ID" IS 'Foreign key identifying the Item Request organization to which the attribute value applies.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_ATTR_VALUE"."ITEM_ATTRIBUTE_ID" IS 'Foreign key identifying the configurable Item Attribute whose transactional value is stored.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_ATTR_VALUE"."VALUE_UOM_CODE" IS 'Optional Unit of Measure code associated with the transactional attribute value. This allows the Unit of Measure to vary by organization.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_ATTR_VALUE"."VALUE_STATUS" IS 'Current processing status of the attribute value. Valid values are DRAFT, READY, PROCESSING, PROCESSED, ERROR and SKIPPED.';
