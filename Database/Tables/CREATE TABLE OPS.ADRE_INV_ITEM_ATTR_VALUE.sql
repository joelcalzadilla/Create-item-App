            value_status IN 
            ( 
                'DRAFT', 
                'READY', 
                'PROCESSING', 
                'PROCESSED', 
                'ERROR', 
                'SKIPPED' 
            ) 
        ) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_ATTR_VALUE_CK3" CHECK ( 
            api_message_count IS NULL 
            OR api_message_count >= 0 
        ) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_ATTR_VALUE_CK4" CHECK ( 
            record_version_number > 0 
        ) ENABLE, 
	 CONSTRAINT "ADRE_INV_ITEM_ATTR_VALUE_PK" PRIMARY KEY ("ITEM_ATTR_VALUE_ID")
