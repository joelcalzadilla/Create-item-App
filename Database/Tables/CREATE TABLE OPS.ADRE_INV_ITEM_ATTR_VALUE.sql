
  CREATE TABLE "ADRE_INV_ITEM_ATTR_VALUE" 
   (	"ITEM_ATTR_VALUE_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"REQUEST_ORG_ID" NUMBER NOT NULL ENABLE, 
	"ITEM_ATTRIBUTE_ID" NUMBER NOT NULL ENABLE, 
	"VALUE_UOM_CODE" VARCHAR2(30), 
	"VALUE_STATUS" VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL ENABLE, 
	"API_RETURN_STATUS" VARCHAR2(10), 
	"API_MESSAGE_COUNT" NUMBER, 
	"API_MESSAGE_TEXT" CLOB, 
	"API_PROCESSED_DATE" DATE, 
	"CREATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"CREATION_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"LAST_UPDATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"LAST_UPDATE_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
