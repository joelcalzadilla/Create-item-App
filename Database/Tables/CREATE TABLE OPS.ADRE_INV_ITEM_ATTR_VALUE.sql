-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Recreate the Item Attribute Value transaction table for the final
-- Adhesives Research Inventory Item Creation application.
--
-- This table stores the actual values entered by the user for
-- configurable Item Attributes associated with an Item Request
-- organization.
--
-- One row represents:
--
--   One Item Request Organization
--   +
--   One configurable Item Attribute
--   +
--   One transactional value
--
-- Values are stored according to their configured data type:
--
--   CHAR / YES_NO -> ATTRIBUTE_CHAR_VALUE
--   NUMBER        -> ATTRIBUTE_NUMBER_VALUE
--   DATE          -> ATTRIBUTE_DATE_VALUE
--
-- VALUE_UOM_CODE allows the Unit of Measure to vary by organization.
--
-- Example:
--
--   GRI / WIDTH  = 29 / INCH
--   IRL / WIDTH  = 1  / METER
--
-- Empty values are allowed while the Item Request remains in DRAFT
-- status.
--
-- Required attribute validation will occur before Send to EBS.
-- =====================================================================


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Drop the existing table when it already exists.
--
-- CASCADE CONSTRAINTS removes foreign key references from previously
-- created dependent application objects during the schema rebuild.
--
-- ORA-00942 is ignored because it means the table does not exist.
-- Any other Oracle error is raised normally.
-- =====================================================================

BEGIN
    EXECUTE IMMEDIATE
        'DROP TABLE ops.adre_inv_item_attr_value CASCADE CONSTRAINTS PURGE';

EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Item Attribute Value transaction table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_attr_value
(
    item_attr_value_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    request_org_id
        NUMBER
        NOT NULL,

    item_attribute_id
        NUMBER
        NOT NULL,

    attribute_char_value
        VARCHAR2(4000),

    attribute_number_value
        NUMBER,

    attribute_date_value
        DATE,

    value_uom_code
        VARCHAR2(30),

    value_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    api_return_status
        VARCHAR2(10),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_attr_value_pk
        PRIMARY KEY
        (
            item_attr_value_id
        ),

    CONSTRAINT adre_inv_item_attr_value_fk1
        FOREIGN KEY
        (
            request_org_id
        )
        REFERENCES ops.adre_inv_item_request_org
        (
            request_org_id
        ),

    CONSTRAINT adre_inv_item_attr_value_fk2
        FOREIGN KEY
        (
            item_attribute_id
        )
        REFERENCES ops.adre_inv_item_attribute
        (
            item_attribute_id
        ),

    CONSTRAINT adre_inv_item_attr_value_u1
        UNIQUE
        (
            request_org_id,
            item_attribute_id
        ),

    CONSTRAINT adre_inv_item_attr_value_ck1
        CHECK
        (
            value_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR',
                'SKIPPED'
            )
        ),

    CONSTRAINT adre_inv_item_attr_value_ck2
        CHECK
        (
              CASE
                  WHEN attribute_char_value IS NOT NULL
                  THEN 1
                  ELSE 0
              END

            + CASE
                  WHEN attribute_number_value IS NOT NULL
                  THEN 1
                  ELSE 0
              END

            + CASE
                  WHEN attribute_date_value IS NOT NULL
                  THEN 1
                  ELSE 0
              END

            <= 1
        ),

    CONSTRAINT adre_inv_item_attr_value_ck3
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),

    CONSTRAINT adre_inv_item_attr_value_ck4
        CHECK
        (
            record_version_number > 0
        )
);


