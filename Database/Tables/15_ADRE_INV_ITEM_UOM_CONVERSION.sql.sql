
  CREATE TABLE "ADRE_INV_ITEM_UOM_CONVERSION" 
   (	"UOM_CONVERSION_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"QUANTITY_KIND" VARCHAR2(10) NOT NULL ENABLE, 
	"FROM_UOM_CODE" VARCHAR2(3) NOT NULL ENABLE, 
	"TO_UOM_CODE" VARCHAR2(3) NOT NULL ENABLE, 
	"FACTOR_NUMERATOR" NUMBER(20,0) NOT NULL ENABLE, 
	"FACTOR_DENOMINATOR" NUMBER(20,0) NOT NULL ENABLE, 
	"ACTIVE_FLAG" VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"CREATION_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	"LAST_UPDATED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"LAST_UPDATE_DATE" DATE DEFAULT SYSDATE NOT NULL ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_CK1" CHECK (quantity_kind IN ('LENGTH', 'WEIGHT')) ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_CK2" CHECK (factor_numerator > 0 AND factor_denominator > 0) ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_CK3" CHECK (from_uom_code <> to_uom_code) ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_CK4" CHECK (active_flag IN ('Y', 'N')) ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_PK" PRIMARY KEY ("UOM_CONVERSION_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "ADRE_INV_UOM_CONV_U1" UNIQUE ("FROM_UOM_CODE", "TO_UOM_CODE")
  USING INDEX  ENABLE
   ) ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "ADRE_INV_UOM_CONV_BIU" 
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_uom_conversion
FOR EACH ROW
DECLARE
    l_actor VARCHAR2(100);
BEGIN
    l_actor := SUBSTR
    (
        NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'),
            SYS_CONTEXT('USERENV', 'SESSION_USER')),
        1,
        100
    );
    IF INSERTING THEN
        :NEW.created_by    := NVL(:NEW.created_by, l_actor);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
    ELSE
        :NEW.created_by    := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
    END IF;
    :NEW.last_updated_by  := l_actor;
    :NEW.last_update_date := SYSDATE;
END;

/
ALTER TRIGGER "ADRE_INV_UOM_CONV_BIU" ENABLE;