CREATE TABLE ops.adre_inv_item_request
(
    item_request_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    request_number
        VARCHAR2(100),

    request_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    item_type_id
        NUMBER
        NOT NULL,

    base_part_number
        VARCHAR2(100),

    item_number
        VARCHAR2(250),

    part_status
        VARCHAR2(30),

    item_description
        VARCHAR2(240),

    long_description
        CLOB,

    primary_uom_code
        VARCHAR2(30),

    item_status_code
        VARCHAR2(30),

    initiator
        VARCHAR2(100),

    requested_creation_date
        DATE,

    forecast_flag
        VARCHAR2(1),

    ebs_submit_date
        DATE,

    api_return_status
        VARCHAR2(10),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_request_pk
        PRIMARY KEY
        (
            item_request_id
        ),

    CONSTRAINT adre_inv_item_request_u1
        UNIQUE
        (
            request_number
        ),

    CONSTRAINT adre_inv_item_request_fk1
        FOREIGN KEY
        (
            item_type_id
        )
        REFERENCES ops.adre_inv_item_type
        (
            item_type_id
        ),

    CONSTRAINT adre_inv_item_request_ck1
        CHECK
        (
            request_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR'
            )
        ),

    CONSTRAINT adre_inv_item_request_ck2
        CHECK
        (
            forecast_flag IS NULL
            OR forecast_flag IN ('Y', 'N')
        ),

    CONSTRAINT adre_inv_item_request_ck3
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),

    CONSTRAINT adre_inv_item_request_ck4
        CHECK
        (
            record_version_number > 0
        )
);


