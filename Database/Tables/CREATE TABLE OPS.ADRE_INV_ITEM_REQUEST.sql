-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Automatically maintain audit information and normalize selected
-- values for ADRE_INV_ITEM_REQUEST.
-- =====================================================================

CREATE OR REPLACE TRIGGER ops.adre_inv_item_request_biu
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_request
FOR EACH ROW

DECLARE

    l_user
        VARCHAR2(100);

    l_login
        VARCHAR2(100);

BEGIN

    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX user when available.
    -- Use the Oracle database user outside an APEX session.
    -- =================================================================

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX session identifier when available.
    -- =================================================================

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize application status values.
    -- =================================================================

    :NEW.request_status :=
        UPPER
        (
            TRIM
            (
                :NEW.request_status
            )
        );


    :NEW.forecast_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.forecast_flag
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize common Oracle EBS code values.
    -- =================================================================

    :NEW.primary_uom_code :=
        UPPER
        (
            TRIM
            (
                :NEW.primary_uom_code
            )
        );


    :NEW.item_status_code :=
        UPPER
        (
            TRIM
            (
                :NEW.item_status_code
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Remove unnecessary leading and trailing spaces from common
    -- business values.
    -- =================================================================

    :NEW.request_number :=
        TRIM
        (
            :NEW.request_number
        );


    :NEW.base_part_number :=
        TRIM
        (
            :NEW.base_part_number
        );


    :NEW.item_number :=
        TRIM
        (
            :NEW.item_number
        );


    :NEW.part_status :=
        TRIM
        (
            :NEW.part_status
        );


    :NEW.item_description :=
        TRIM
        (
            :NEW.item_description
        );


    :NEW.initiator :=
        TRIM
        (
            :NEW.initiator
        );


    IF INSERTING THEN

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize creation audit information for a new Item Request.
        -- =============================================================

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );


        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize the first row version.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );

    ELSE

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Preserve the original creation audit information.
        -- =============================================================

        :NEW.created_by :=
            :OLD.created_by;

        :NEW.creation_date :=
            :OLD.creation_date;


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Increment the row version number on every update.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;

    END IF;


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Refresh last-update audit information.
    -- =================================================================

    :NEW.last_updated_by :=
        l_user;

    :NEW.last_update_date :=
        SYSDATE;

    :NEW.last_update_login :=
        l_login;

END;
/

