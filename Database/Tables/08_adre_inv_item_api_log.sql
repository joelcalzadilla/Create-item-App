    CONSTRAINT adre_inv_item_api_log_ck7 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_api_log_pk PRIMARY KEY (item_api_log_id) USING INDEX ENABLE
