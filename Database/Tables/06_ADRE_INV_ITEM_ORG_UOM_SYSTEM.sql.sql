
  CREATE TABLE "ADRE_INV_ITEM_ORG_UOM_SYSTEM" 
   (	"ORG_UOM_SYSTEM_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
