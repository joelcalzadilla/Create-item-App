   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."ITEM_SECTION_ID" IS 'Surrogate primary key generated by Oracle for each Organization Details section.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."SECTION_CODE" IS 'Unique internal application code used to identify the Organization Details section.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."SECTION_NAME" IS 'User-facing section name displayed in the Oracle APEX Organization Details modal.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."SECTION_TYPE" IS 'Processing type for the section. Valid values are ATTRIBUTE, CATEGORY, BOM and DOCUMENT.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."ORGANIZATION_SCOPE" IS 'Defines whether the section applies to MASTER organizations, TARGET organizations or BOTH.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."ACTIVE_FLAG" IS 'Indicates whether the section is available for use in the application. Valid values are Y and N.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."DISPLAY_SEQUENCE" IS 'Controls the display order of sections in the Oracle APEX Organization Details modal.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."CREATED_BY" IS 'Creator identity supplied on insert or resolved from APEX APP_USER, falling back to the database user. Preserved on update.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."CREATION_DATE" IS 'Creation date and time, initialized on insert and preserved on update.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."LAST_UPDATED_BY" IS 'User responsible for the latest insert or update, resolved from APEX APP_USER or the database user.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."LAST_UPDATE_DATE" IS 'Database date and time of the latest insert or update, maintained by the audit trigger.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."LAST_UPDATE_LOGIN" IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';
   COMMENT ON COLUMN "ADRE_INV_ITEM_SECTION"."RECORD_VERSION_NUMBER" IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';
   COMMENT ON TABLE "ADRE_INV_ITEM_SECTION"  IS 'Configuration table containing the Organization Details sections displayed by the Adhesives Research Inventory Item Creation application.';

  CREATE OR REPLACE EDITIONABLE TRIGGER "ADRE_INV_ITEM_SECTION_BIU" 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_section
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN
    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );
    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );
    :NEW.section_code :=
        UPPER
        (
            TRIM
            (
                :NEW.section_code
            )
        );
    :NEW.section_name :=
        TRIM
        (
            :NEW.section_name
        );
    :NEW.section_type :=
        UPPER
        (
            TRIM
            (
                :NEW.section_type
            )
        );
    :NEW.organization_scope :=
        UPPER
        (
            TRIM
            (
                :NEW.organization_scope
            )
        );
    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );
    IF INSERTING THEN
        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );
        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE
        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;
        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;
    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/
ALTER TRIGGER "ADRE_INV_ITEM_SECTION_BIU" ENABLE;