CREATE TABLE ops.adre_inv_item_section
(
    item_section_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    section_code VARCHAR2(50) NOT NULL ENABLE,
    section_name VARCHAR2(100) NOT NULL ENABLE,
    section_type VARCHAR2(30) NOT NULL ENABLE,
    organization_scope VARCHAR2(30) DEFAULT 'BOTH' NOT NULL ENABLE,
    active_flag VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE,
    display_sequence NUMBER DEFAULT 10 NOT NULL ENABLE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    CONSTRAINT adre_inv_item_section_ck1 CHECK ( section_type IN ( 'ATTRIBUTE', 'CATEGORY', 'BOM', 'DOCUMENT' ) ) ENABLE,
    CONSTRAINT adre_inv_item_section_ck2 CHECK ( organization_scope IN ( 'MASTER', 'TARGET', 'BOTH' ) ) ENABLE,
    CONSTRAINT adre_inv_item_section_ck3 CHECK ( active_flag IN ( 'Y', 'N' ) ) ENABLE,
    CONSTRAINT adre_inv_item_section_ck4 CHECK ( display_sequence > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_section_ck5 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_section_pk PRIMARY KEY (item_section_id) USING INDEX ENABLE
);

CREATE INDEX ops.adre_inv_item_section_n1 ON ops.adre_inv_item_section (active_flag, display_sequence) 
  ;

CREATE INDEX ops.adre_inv_item_section_n2 ON ops.adre_inv_item_section (organization_scope, active_flag) 
  ;

CREATE INDEX ops.adre_inv_item_section_n3 ON ops.adre_inv_item_section (section_type, active_flag) 
  ;

COMMENT ON COLUMN ops.adre_inv_item_section.item_section_id IS 'Surrogate primary key generated by Oracle for each Organization Details section.';

COMMENT ON COLUMN ops.adre_inv_item_section.section_code IS 'Unique internal application code used to identify the Organization Details section.';

COMMENT ON COLUMN ops.adre_inv_item_section.section_name IS 'User-facing section name displayed in the Oracle APEX Organization Details modal.';

COMMENT ON COLUMN ops.adre_inv_item_section.section_type IS 'Processing type for the section. Valid values are ATTRIBUTE, CATEGORY, BOM and DOCUMENT.';

COMMENT ON COLUMN ops.adre_inv_item_section.organization_scope IS 'Defines whether the section applies to MASTER organizations, TARGET organizations or BOTH.';

COMMENT ON COLUMN ops.adre_inv_item_section.active_flag IS 'Indicates whether the section is available for use in the application. Valid values are Y and N.';

COMMENT ON COLUMN ops.adre_inv_item_section.display_sequence IS 'Controls the display order of sections in the Oracle APEX Organization Details modal.';

COMMENT ON TABLE ops.adre_inv_item_section  IS 'Configuration table containing the Organization Details sections displayed by the Adhesives Research Inventory Item Creation application.';

CREATE UNIQUE INDEX ops.adre_inv_item_section_u1 ON ops.adre_inv_item_section (section_code);

CREATE UNIQUE INDEX ops.adre_inv_item_section_u2 ON ops.adre_inv_item_section (section_name);

COMMENT ON COLUMN ops.adre_inv_item_section.created_by IS 'Creator identity supplied on insert or resolved from APEX APP_USER, falling back to the database user. Preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_section.creation_date IS 'Creation date and time, initialized on insert and preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_section.last_updated_by IS 'User responsible for the latest insert or update, resolved from APEX APP_USER or the database user.';

COMMENT ON COLUMN ops.adre_inv_item_section.last_update_date IS 'Database date and time of the latest insert or update, maintained by the audit trigger.';

COMMENT ON COLUMN ops.adre_inv_item_section.last_update_login IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';

COMMENT ON COLUMN ops.adre_inv_item_section.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_section_biu 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_section
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );

    :NEW.section_code :=
        UPPER
        (
            TRIM
            (
                :NEW.section_code
            )
        );

    :NEW.section_name :=
        TRIM
        (
            :NEW.section_name
        );

    :NEW.section_type :=
        UPPER
        (
            TRIM
            (
                :NEW.section_type
            )
        );

    :NEW.organization_scope :=
        UPPER
        (
            TRIM
            (
                :NEW.organization_scope
            )
        );

    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );
    IF INSERTING THEN

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE

        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;

    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/

ALTER TRIGGER ops.adre_inv_item_section_biu ENABLE;
