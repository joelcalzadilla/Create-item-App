COMMENT ON COLUMN ops.adre_inv_item_type.ebs_security_group_id IS 'Oracle EBS security group identifier associated with the item type view.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_type_biu 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_type
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );

    :NEW.item_type_code :=
        UPPER
        (
            TRIM
            (
                :NEW.item_type_code
            )
        );

    :NEW.item_type_name :=
        TRIM
        (
            :NEW.item_type_name
        );
    IF INSERTING THEN

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE

        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;

    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/

ALTER TRIGGER ops.adre_inv_item_type_biu ENABLE;
