COMMENT ON COLUMN ops.adre_inv_item_type.item_type_code IS 'Unique application code used internally to identify the Item Type.';

COMMENT ON COLUMN ops.adre_inv_item_type.item_type_name IS 'User-facing Item Type name displayed in Oracle APEX.';

COMMENT ON COLUMN ops.adre_inv_item_type.description IS 'Functional description of the Item Type.';

COMMENT ON COLUMN ops.adre_inv_item_type.active_flag IS 'Indicates whether the Item Type is available for use. Valid values are Y and N.';

COMMENT ON COLUMN ops.adre_inv_item_type.display_sequence IS 'Controls the display order of Item Types in Oracle APEX.';

COMMENT ON TABLE ops.adre_inv_item_type  IS 'Configuration table containing the Item Types available in the Adhesives Research Inventory Item Creation application.';

CREATE UNIQUE INDEX ops.adre_inv_item_type_u1 ON ops.adre_inv_item_type (item_type_code);

COMMENT ON COLUMN ops.adre_inv_item_type.created_by IS 'Creator identity supplied on insert or resolved from APEX APP_USER, falling back to the database user. Preserved on update.';

