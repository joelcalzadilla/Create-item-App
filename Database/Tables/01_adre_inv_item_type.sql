COMMENT ON COLUMN ops.adre_inv_item_type.last_update_login IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';

COMMENT ON COLUMN ops.adre_inv_item_type.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

