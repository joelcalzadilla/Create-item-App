CREATE TABLE ops.adre_inv_item_type
(
    item_type_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    item_type_code VARCHAR2(50) NOT NULL ENABLE,
    item_type_name VARCHAR2(240) NOT NULL ENABLE,
    description VARCHAR2(1000),
    active_flag VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE,
    display_sequence NUMBER DEFAULT 10 NOT NULL ENABLE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    ebs_item_type_code VARCHAR2(30),
    ebs_view_application_id NUMBER,
    ebs_security_group_id NUMBER,
    CONSTRAINT adre_inv_item_type_ck1 CHECK ( active_flag IN ('Y', 'N') ) ENABLE,
    CONSTRAINT adre_inv_item_type_ck2 CHECK ( display_sequence > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_type_ck3 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_type_pk PRIMARY KEY (item_type_id) USING INDEX ENABLE
);

CREATE INDEX ops.adre_inv_item_type_n1 ON ops.adre_inv_item_type (active_flag, display_sequence) 
  ;

