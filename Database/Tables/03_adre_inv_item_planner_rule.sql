COMMENT ON COLUMN ops.adre_inv_item_planner_rule.last_update_date IS 'Database date and time of the latest insert or update, maintained by the audit trigger.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.last_update_login IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

CREATE OR REPLACE TRIGGER ops.adre_inv_item_planner_rule_biu
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_planner_rule
FOR EACH ROW
DECLARE
    l_user VARCHAR2(100);
    l_login VARCHAR2(100);
BEGIN
    l_user := SUBSTR(NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER), 1, 100);
    l_login := SUBSTR(NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER), 1, 100);
    IF INSERTING THEN
        :NEW.created_by := NVL(:NEW.created_by, l_user);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1);
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1;
    END IF;
    :NEW.last_updated_by := l_user;
    :NEW.last_update_date := SYSDATE;
    :NEW.last_update_login := l_login;
END;
