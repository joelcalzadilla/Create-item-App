CREATE TABLE ops.adre_inv_item_planner_rule
(
    planner_rule_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    item_type_id NUMBER NOT NULL ENABLE,
    organization_id NUMBER,
    item_prefix VARCHAR2(100),
    planner_code VARCHAR2(30) NOT NULL ENABLE,
    priority NUMBER DEFAULT 100 NOT NULL ENABLE,
    active_flag VARCHAR2(1) DEFAULT 'N' NOT NULL ENABLE,
    effective_from_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    effective_to_date DATE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT adre_inv_plnr_rule_ver_ck CHECK (record_version_number > 0),
    CONSTRAINT adre_inv_plnr_rule_active_ck CHECK (active_flag IN ('Y', 'N')) ENABLE,
    CONSTRAINT adre_inv_plnr_rule_prio_ck CHECK (priority >= 0 AND priority = TRUNC(priority)) ENABLE,
    CONSTRAINT adre_inv_plnr_rule_dates_ck CHECK ( effective_to_date IS NULL OR effective_to_date > effective_from_date ) ENABLE,
    CONSTRAINT adre_inv_plnr_rule_prefix_ck CHECK ( item_prefix IS NULL OR ( TRIM(item_prefix) IS NOT NULL AND item_prefix = UPPER(TRIM(item_prefix)) ) ) ENABLE,
    CONSTRAINT adre_inv_plnr_rule_code_ck CHECK ( TRIM(planner_code) IS NOT NULL AND planner_code = TRIM(planner_code) ) ENABLE,
    CONSTRAINT adre_inv_plnr_rule_pk PRIMARY KEY (planner_rule_id) USING INDEX ENABLE
);

ALTER TABLE ops.adre_inv_item_planner_rule ADD CONSTRAINT adre_inv_plnr_rule_type_fk FOREIGN KEY (item_type_id)
	  REFERENCES ops.adre_inv_item_type (item_type_id) ENABLE;

CREATE INDEX ops.adre_inv_plnr_rule_n1 ON ops.adre_inv_item_planner_rule (item_type_id, active_flag, priority) 
  ;

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.planner_rule_id IS 'Generated primary key of the Planner rule; never used to break precedence ties.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.item_type_id IS 'Existing OPS Item Type identifier. Names are resolved through ADRE_INV_ITEM_TYPE.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.organization_id IS 'Oracle EBS Target Organization identifier. NULL applies to every Target Organization. Validate against EBS metadata at use.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.item_prefix IS 'Uppercase trimmed text before the first hyphen in the item number. NULL matches every prefix.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.planner_code IS 'Business Planner value resolved uniquely to an active MTL_PLANNERS code in the actual Target Organization; retains existing leading-zero matching.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.priority IS 'Nonnegative integer priority. The lowest applicable value wins; specificity is expressed by configuration priority.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.active_flag IS 'Y enables the rule subject to effective dates and existing AUTO_DERIVE_FLAG configuration; N disables it.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.effective_from_date IS 'Inclusive effective start date and time, using the database clock.';

COMMENT ON COLUMN ops.adre_inv_item_planner_rule.effective_to_date IS 'Exclusive effective end date and time. NULL means no scheduled end.';

COMMENT ON TABLE ops.adre_inv_item_planner_rule  IS 'Automatic Planner rules by application Item Type, optional Target Organization and optional item prefix. Lower numeric priority wins; equal winning priorities are configuration errors.';

