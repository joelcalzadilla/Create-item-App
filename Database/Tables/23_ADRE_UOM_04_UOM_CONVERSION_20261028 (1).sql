CREATE TABLE ops.adre_inv_item_uom_conversion
(
    uom_conversion_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    quantity_kind     VARCHAR2(10) NOT NULL,
    from_uom_code     VARCHAR2(3) NOT NULL,
    to_uom_code       VARCHAR2(3) NOT NULL,
    factor_numerator  NUMBER(20,0) NOT NULL,
    factor_denominator NUMBER(20,0) NOT NULL,
    active_flag       VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by        VARCHAR2(100) NOT NULL,
    creation_date     DATE DEFAULT SYSDATE NOT NULL,
    last_updated_by   VARCHAR2(100) NOT NULL,
    last_update_date  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT adre_inv_uom_conv_pk PRIMARY KEY (uom_conversion_id),
    CONSTRAINT adre_inv_uom_conv_u1 UNIQUE (from_uom_code, to_uom_code),
    CONSTRAINT adre_inv_uom_conv_ck1 CHECK (quantity_kind IN ('LENGTH', 'WEIGHT')),
    CONSTRAINT adre_inv_uom_conv_ck2 CHECK (factor_numerator > 0 AND factor_denominator > 0),
    CONSTRAINT adre_inv_uom_conv_ck3 CHECK (from_uom_code <> to_uom_code),
    CONSTRAINT adre_inv_uom_conv_ck4 CHECK (active_flag IN ('Y', 'N'))
);

-- Maintain creation and last-update metadata on this configuration table.
CREATE OR REPLACE TRIGGER ops.adre_inv_uom_conv_biu
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_uom_conversion
FOR EACH ROW
DECLARE
    l_actor VARCHAR2(100);
BEGIN
    l_actor := SUBSTR
    (
        NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'),
            SYS_CONTEXT('USERENV', 'SESSION_USER')),
        1,
        100
    );

    IF INSERTING THEN
        :NEW.created_by    := NVL(:NEW.created_by, l_actor);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
    ELSE
        :NEW.created_by    := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
    END IF;

    :NEW.last_updated_by  := l_actor;
    :NEW.last_update_date := SYSDATE;
END;
/
