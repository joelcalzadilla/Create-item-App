CREATE TABLE ops.adre_inv_item_request
(
    item_request_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 215 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    request_number VARCHAR2(100),
    request_status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL ENABLE,
    item_type_id NUMBER NOT NULL ENABLE,
    base_part_number VARCHAR2(100),
    item_number VARCHAR2(250),
    part_status VARCHAR2(30),
    item_description VARCHAR2(240),
    long_description CLOB,
    primary_uom_code VARCHAR2(30),
    item_status_code VARCHAR2(30),
    initiator VARCHAR2(100),
    requested_creation_date DATE,
    forecast_flag VARCHAR2(1),
    ebs_submit_date DATE,
    api_return_status VARCHAR2(10),
    api_message_count NUMBER,
    api_message_text CLOB,
    api_processed_date DATE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    CONSTRAINT adre_inv_item_request_ck1 CHECK ( request_status IN ( 'DRAFT', 'READY', 'PROCESSING', 'PROCESSED', 'ERROR' ) ) ENABLE,
    CONSTRAINT adre_inv_item_request_ck2 CHECK ( forecast_flag IS NULL OR forecast_flag IN ('Y', 'N') ) ENABLE,
    CONSTRAINT adre_inv_item_request_ck3 CHECK ( api_message_count IS NULL OR api_message_count >= 0 ) ENABLE,
    CONSTRAINT adre_inv_item_request_ck4 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_request_pk PRIMARY KEY (item_request_id) USING INDEX ENABLE
);

