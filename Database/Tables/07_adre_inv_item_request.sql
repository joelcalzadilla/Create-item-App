CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_request_biu 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_request
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );

    :NEW.request_status :=
        UPPER
        (
            TRIM
            (
                :NEW.request_status
            )
        );
    :NEW.forecast_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.forecast_flag
            )
        );

    :NEW.primary_uom_code :=
        UPPER
        (
            TRIM
            (
                :NEW.primary_uom_code
            )
        );
    :NEW.item_status_code :=
        UPPER
        (
            TRIM
            (
                :NEW.item_status_code
            )
        );

    :NEW.request_number :=
        TRIM
        (
            :NEW.request_number
        );
    :NEW.base_part_number :=
        TRIM
        (
            :NEW.base_part_number
        );
    :NEW.item_number :=
        TRIM
        (
            :NEW.item_number
        );
    :NEW.part_status :=
        TRIM
        (
            :NEW.part_status
        );
    :NEW.item_description :=
        TRIM
        (
            :NEW.item_description
        );
    :NEW.initiator :=
        TRIM
        (
            :NEW.initiator
        );
    IF INSERTING THEN

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE

        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;

    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/

ALTER TRIGGER ops.adre_inv_item_request_biu ENABLE;
