-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Item Type configuration table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_type
(
    item_type_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    item_type_code
        VARCHAR2(50)
        NOT NULL,

    item_type_name
        VARCHAR2(240)
        NOT NULL,

    description
        VARCHAR2(1000),

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_type_pk
        PRIMARY KEY
        (
            item_type_id
        ),

    CONSTRAINT adre_inv_item_type_u1
        UNIQUE
        (
            item_type_code
        ),

    CONSTRAINT adre_inv_item_type_ck1
        CHECK
        (
            active_flag IN ('Y', 'N')
        ),

    CONSTRAINT adre_inv_item_type_ck2
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_type_ck3
        CHECK
        (
            record_version_number > 0
        )
);


