-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Automatically maintain audit information for ADRE_INV_ITEM_TYPE.
--
-- The trigger also normalizes ITEM_TYPE_CODE so the application stores
-- Item Type codes consistently in uppercase without leading or trailing
-- spaces.
--
-- ITEM_TYPE_NAME is trimmed before being stored.
-- =====================================================================

CREATE OR REPLACE TRIGGER ops.adre_inv_item_type_biu
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_type
FOR EACH ROW

DECLARE

    l_user
        VARCHAR2(100);

    l_login
        VARCHAR2(100);

BEGIN

    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX user when the DML originates from APEX.
    --
    -- When the operation is executed outside Oracle APEX, use the
    -- current Oracle database user.
    -- =================================================================

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX session identifier when available.
    --
    -- When no APEX session exists, use the current Oracle database
    -- user as the fallback value.
    -- =================================================================

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the Item Type code before storing the row.
    --
    -- Example:
    -- adhesive_coating
    --
    -- becomes:
    -- ADHESIVE_COATING
    -- =================================================================

    :NEW.item_type_code :=
        UPPER
        (
            TRIM
            (
                :NEW.item_type_code
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Remove unnecessary leading and trailing spaces from the Item Type
    -- display name.
    -- =================================================================

    :NEW.item_type_name :=
        TRIM
        (
            :NEW.item_type_name
        );


    IF INSERTING THEN

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize creation audit information for a new row.
        -- =============================================================

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );


        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize the first row version.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );

    ELSE

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Preserve the original creation audit information when an
        -- existing Item Type is updated.
        -- =============================================================

        :NEW.created_by :=
            :OLD.created_by;

        :NEW.creation_date :=
            :OLD.creation_date;


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Increment the row version number after each update.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;

    END IF;


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Refresh the last-update audit information for both inserts and
    -- updates.
    -- =================================================================

    :NEW.last_updated_by :=
        l_user;

    :NEW.last_update_date :=
        SYSDATE;

    :NEW.last_update_login :=
        l_login;

END;
/

