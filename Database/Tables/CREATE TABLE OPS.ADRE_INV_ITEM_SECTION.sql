-- Create the Organization Details Section configuration table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_section
(
    item_section_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    section_code
        VARCHAR2(50)
        NOT NULL,

    section_name
        VARCHAR2(100)
        NOT NULL,

    section_type
        VARCHAR2(30)
        NOT NULL,

    organization_scope
        VARCHAR2(30)
        DEFAULT 'BOTH'
        NOT NULL,

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_section_pk
        PRIMARY KEY
        (
            item_section_id
        ),

    CONSTRAINT adre_inv_item_section_u1
        UNIQUE
        (
            section_code
        ),

    CONSTRAINT adre_inv_item_section_u2
        UNIQUE
        (
            section_name
        ),

    CONSTRAINT adre_inv_item_section_ck1
        CHECK
        (
            section_type IN
            (
                'ATTRIBUTE',
                'CATEGORY',
                'BOM',
                'DOCUMENT'
            )
        ),

    CONSTRAINT adre_inv_item_section_ck2
        CHECK
        (
            organization_scope IN
            (
                'MASTER',
                'TARGET',
                'BOTH'
            )
        ),

    CONSTRAINT adre_inv_item_section_ck3
        CHECK
        (
            active_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_section_ck4
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_section_ck5
        CHECK
        (
            record_version_number > 0
        )
);


