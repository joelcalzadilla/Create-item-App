-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Automatically maintain audit information and normalize Organization
-- Details Section configuration values for ADRE_INV_ITEM_SECTION.
-- =====================================================================

CREATE OR REPLACE TRIGGER ops.adre_inv_item_section_biu
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_section
FOR EACH ROW

DECLARE

    l_user
        VARCHAR2(100);

    l_login
        VARCHAR2(100);

BEGIN

    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX user when available.
    --
    -- Use the current Oracle database user when the operation is
    -- executed outside Oracle APEX.
    -- =================================================================

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX session identifier when available.
    -- =================================================================

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the internal section code.
    --
    -- Example:
    -- physical_attributes
    --
    -- becomes:
    -- PHYSICAL_ATTRIBUTES
    -- =================================================================

    :NEW.section_code :=
        UPPER
        (
            TRIM
            (
                :NEW.section_code
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Preserve the user-facing section name while removing unnecessary
    -- leading and trailing spaces.
    -- =================================================================

    :NEW.section_name :=
        TRIM
        (
            :NEW.section_name
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the section processing type.
    -- =================================================================

    :NEW.section_type :=
        UPPER
        (
            TRIM
            (
                :NEW.section_type
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the organization scope.
    -- =================================================================

    :NEW.organization_scope :=
        UPPER
        (
            TRIM
            (
                :NEW.organization_scope
            )
        );


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Normalize the active indicator.
    -- =================================================================

    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );


    IF INSERTING THEN

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize creation audit information for a new section.
        -- =============================================================

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );


        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Initialize the first row version.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );

    ELSE

        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Preserve the original creation audit information.
        -- =============================================================

        :NEW.created_by :=
            :OLD.created_by;

        :NEW.creation_date :=
            :OLD.creation_date;


        -- =============================================================
        -- JCALZADILLA - 22.08.2026
        -- Increment the row version number on every update.
        -- =============================================================

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;

    END IF;


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Refresh the last-update audit information for inserts and updates.
    -- =================================================================

    :NEW.last_updated_by :=
        l_user;

    :NEW.last_update_date :=
        SYSDATE;

    :NEW.last_update_login :=
        l_login;

END;
/

