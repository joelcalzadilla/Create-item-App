CREATE TABLE ops.adre_inv_item_attribute
(
    item_attribute_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    item_section_id NUMBER NOT NULL ENABLE,
    attribute_code VARCHAR2(100) NOT NULL ENABLE,
    attribute_name VARCHAR2(240) NOT NULL ENABLE,
    attribute_data_type VARCHAR2(30) NOT NULL ENABLE,
    description VARCHAR2(1000),
    default_value VARCHAR2(1000),
    unit_of_measure VARCHAR2(30),
    required_flag VARCHAR2(1) DEFAULT 'N' NOT NULL ENABLE,
    active_flag VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE,
    display_sequence NUMBER DEFAULT 10 NOT NULL ENABLE,
    ebs_attribute_name VARCHAR2(240),
    ebs_attribute_group VARCHAR2(240),
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    CONSTRAINT adre_inv_item_attribute_ck1 CHECK ( attribute_data_type IN ( 'CHAR', 'NUMBER', 'DATE', 'YES_NO' ) ) ENABLE,
    CONSTRAINT adre_inv_item_attribute_ck2 CHECK ( required_flag IN ( 'Y', 'N' ) ) ENABLE,
    CONSTRAINT adre_inv_item_attribute_ck3 CHECK ( active_flag IN ( 'Y', 'N' ) ) ENABLE,
    CONSTRAINT adre_inv_item_attribute_ck4 CHECK ( display_sequence > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_attribute_ck5 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_attribute_pk PRIMARY KEY (item_attribute_id) USING INDEX ENABLE
);

