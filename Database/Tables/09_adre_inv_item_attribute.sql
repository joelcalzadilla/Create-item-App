COMMENT ON COLUMN ops.adre_inv_item_attribute.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_attribute_biu 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_attribute
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );

    :NEW.attribute_code :=
        UPPER
        (
            TRIM
            (
                :NEW.attribute_code
            )
        );

    :NEW.attribute_name :=
        TRIM
        (
            :NEW.attribute_name
        );

    :NEW.attribute_data_type :=
        UPPER
        (
            TRIM
            (
                :NEW.attribute_data_type
            )
        );

    :NEW.unit_of_measure :=
        UPPER
        (
            TRIM
            (
                :NEW.unit_of_measure
            )
        );

    :NEW.required_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.required_flag
            )
        );
    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );

    :NEW.ebs_attribute_name :=
        TRIM
        (
            :NEW.ebs_attribute_name
        );
    :NEW.ebs_attribute_group :=
        TRIM
        (
            :NEW.ebs_attribute_group
        );
    IF INSERTING THEN

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE

        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;

    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/

ALTER TRIGGER ops.adre_inv_item_attribute_biu ENABLE;

