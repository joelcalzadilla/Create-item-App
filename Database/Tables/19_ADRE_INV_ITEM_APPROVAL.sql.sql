  CREATE OR REPLACE EDITIONABLE TRIGGER "ADRE_INV_ITEM_APPROVAL_BIU" 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_approval
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN
    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );
    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );
    :NEW.approval_type :=
        UPPER
        (
            TRIM
            (
                :NEW.approval_type
            )
        );
    :NEW.approval_status :=
        UPPER
        (
            TRIM
            (
                NVL
                (
                    :NEW.approval_status,
                    'PENDING'
                )
            )
        );
    IF INSERTING THEN
        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );
        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;
    :NEW.last_updated_by :=
        NVL
        (
            l_user,
            :NEW.last_updated_by
        );
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

