  CREATE OR REPLACE EDITIONABLE TRIGGER "ADRE_INV_ITEM_BOM_COMP_BIU" 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_bom_comp
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN
    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );
    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );
    :NEW.component_item_number :=
        UPPER
        (
            TRIM
            (
                :NEW.component_item_number
            )
        );
    :NEW.component_uom_code :=
        UPPER
        (
            TRIM
            (
                :NEW.component_uom_code
            )
        );
    :NEW.supply_type :=
        UPPER
        (
            TRIM
            (
                :NEW.supply_type
            )
        );
    :NEW.component_status :=
        UPPER
        (
            TRIM
            (
                :NEW.component_status
            )
        );
    :NEW.api_return_status :=
        UPPER
        (
            TRIM
            (
                :NEW.api_return_status
            )
        );
    IF INSERTING THEN
        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );
        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE
        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;
        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;
    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/
ALTER TRIGGER "ADRE_INV_ITEM_BOM_COMP_BIU" ENABLE;