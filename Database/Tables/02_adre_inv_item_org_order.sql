CREATE TABLE ops.adre_inv_item_org_order
(
    pk_org_order_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 215 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    ebs_organization_id NUMBER NOT NULL ENABLE,
    display_sequence NUMBER NOT NULL ENABLE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    CONSTRAINT adre_inv_item_org_order_pk PRIMARY KEY (pk_org_order_id) USING INDEX ENABLE,
    CONSTRAINT adre_inv_item_org_order_ver_ck CHECK (record_version_number > 0) ENABLE
);

CREATE UNIQUE INDEX ops.adre_inv_item_org_order_u1 ON ops.adre_inv_item_org_order (ebs_organization_id) 
  ;

COMMENT ON COLUMN ops.adre_inv_item_org_order.pk_org_order_id IS 'Automatically generated surrogate primary key. Has no business meaning.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.ebs_organization_id IS 'EBS target inventory organization identifier. Uniquely identifies the organization in the display order configuration. The validation trigger permits active non-master organizations only.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.display_sequence IS 'Display order for the target organization. Lower values appear first. The original definition does not require unique or positive sequence values.';

COMMENT ON TABLE ops.adre_inv_item_org_order  IS 'Display order configuration for active EBS target inventory organizations, with one row per organization and audit metadata.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.created_by IS 'Creator identity supplied on insert or resolved from APEX APP_USER, falling back to the database user. Preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.creation_date IS 'Creation date and time, initialized on insert and preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.last_updated_by IS 'User responsible for the latest insert or update, resolved from APEX APP_USER or the database user.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.last_update_date IS 'Database date and time of the latest insert or update, maintained by the audit trigger.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.last_update_login IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';

COMMENT ON COLUMN ops.adre_inv_item_org_order.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_org_order_aud_biu 
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_org_order 
FOR EACH ROW 
DECLARE 
    l_user  VARCHAR2(100); 
    l_login VARCHAR2(100); 
BEGIN 
    l_user  := SUBSTR(NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER), 1, 100); 
    l_login := SUBSTR(NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER), 1, 100); 
 
    IF INSERTING THEN 
        :NEW.created_by            := NVL(:NEW.created_by, l_user); 
        :NEW.creation_date         := NVL(:NEW.creation_date, SYSDATE); 
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1); 
    ELSE 
        :NEW.created_by            := :OLD.created_by; 
        :NEW.creation_date         := :OLD.creation_date; 
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1; 
    END IF; 
 
    :NEW.last_updated_by   := l_user; 
    :NEW.last_update_date  := SYSDATE; 
    :NEW.last_update_login := l_login; 
END; 

/

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_org_order_biu 
BEFORE INSERT OR UPDATE OF ebs_organization_id, display_sequence 
ON ops.adre_inv_item_org_order 
FOR EACH ROW 
DECLARE 
    l_count NUMBER; 
BEGIN 

    SELECT COUNT(*) 
      INTO l_count 
      FROM apps.mtl_parameters mp, 
           apps.hr_all_organization_units hou 
     WHERE hou.organization_id = mp.organization_id 
       AND mp.organization_id = :NEW.ebs_organization_id 
       AND mp.organization_id <> mp.master_organization_id 
       AND (hou.date_from IS NULL OR hou.date_from <= TRUNC(SYSDATE)) 
       AND (hou.date_to IS NULL OR hou.date_to >= TRUNC(SYSDATE)); 
    IF l_count <> 1 THEN 
        raise_application_error( 
            -20001, 
            'The organization must be an active EBS target organization.' 
        ); 
    END IF; 
END; 

/

ALTER TRIGGER ops.adre_inv_item_org_order_aud_biu ENABLE;

ALTER TRIGGER ops.adre_inv_item_org_order_biu ENABLE;
