-- Adhesives Research
-- Script  : 28_adre_inv_item_uom_default.sql
-- Purpose : Resolve one default UOM per item type and user UOM system.
-- Order   : 28. Run once after Tables/27.
-- One approved UOM may be the default for both IMPERIAL and METRIC.
-- DEFAULT_UOM_SYSTEM in TYPE_UOM is retained for DEV compatibility.
-- This table is the authoritative mapping used by the package.

CREATE TABLE ops.adre_inv_item_uom_default
(
    uom_default_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    item_type_id          NUMBER NOT NULL,
    preferred_uom_system  VARCHAR2(20) NOT NULL,
    item_type_uom_id      NUMBER NOT NULL,
    active_flag           VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by            VARCHAR2(100) NOT NULL,
    creation_date         DATE DEFAULT SYSDATE NOT NULL,
    last_updated_by       VARCHAR2(100) NOT NULL,
    last_update_date      DATE DEFAULT SYSDATE NOT NULL,
    last_update_login     VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT adre_uom_default_pk PRIMARY KEY (uom_default_id),
    CONSTRAINT adre_uom_default_u1 UNIQUE (item_type_id, preferred_uom_system),
    CONSTRAINT adre_uom_default_c1 CHECK (preferred_uom_system IN ('IMPERIAL', 'METRIC')),
    CONSTRAINT adre_uom_default_c2 CHECK (active_flag IN ('Y', 'N')),
    CONSTRAINT adre_uom_default_c3 CHECK (record_version_number > 0),
    CONSTRAINT adre_uom_default_f1 FOREIGN KEY (item_type_id)
        REFERENCES ops.adre_inv_item_type (item_type_id),
    CONSTRAINT adre_uom_default_f2 FOREIGN KEY (item_type_uom_id)
        REFERENCES ops.adre_inv_item_type_uom (item_type_uom_id)
);

CREATE INDEX ops.adre_uom_default_n1
    ON ops.adre_inv_item_uom_default (item_type_uom_id, active_flag);

COMMENT ON TABLE ops.adre_inv_item_uom_default IS
    'Selects an approved default UOM for an item type and user UOM system. The package validates that ITEM_TYPE_UOM_ID belongs to ITEM_TYPE_ID and is active.';
COMMENT ON COLUMN ops.adre_inv_item_type_uom.default_uom_system IS
    'Transitional preference marker retained for existing data. The authoritative default per item type and system is OPS.ADRE_INV_ITEM_UOM_DEFAULT.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.uom_default_id IS
    'Surrogate identifier of the default UOM mapping.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.item_type_id IS
    'Application item type for this UOM preference.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.preferred_uom_system IS
    'IMPERIAL or METRIC user preference.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.item_type_uom_id IS
    'Approved UOM row for this type; the same row may serve both user systems.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.active_flag IS
    'Y makes this default UOM available for new requests.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.created_by IS
    'Creator identity resolved from APEX APP_USER or database user, preserved on update.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.creation_date IS
    'Creation date and time, preserved on update.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.last_updated_by IS
    'Identity responsible for the latest insert or update.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.last_update_date IS
    'Database date and time of the latest insert or update.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.last_update_login IS
    'APEX APP_SESSION for the latest update; database user outside APEX.';
COMMENT ON COLUMN ops.adre_inv_item_uom_default.record_version_number IS
    'Positive row version incremented on each update.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.trg_adre_uom_default
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_uom_default
FOR EACH ROW
DECLARE
    l_user  VARCHAR2(100);
    l_login VARCHAR2(100);
    l_type_id NUMBER;
    l_active  VARCHAR2(1);
BEGIN
    l_user := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    l_login := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER);
    :NEW.preferred_uom_system := UPPER(TRIM(:NEW.preferred_uom_system));
    :NEW.active_flag := UPPER(TRIM(:NEW.active_flag));

    SELECT cfg.item_type_id, cfg.active_flag
      INTO l_type_id, l_active
      FROM ops.adre_inv_item_type_uom cfg
     WHERE cfg.item_type_uom_id = :NEW.item_type_uom_id;
    IF l_type_id <> :NEW.item_type_id OR l_active <> 'Y' THEN
        raise_application_error(-20130, 'Default UOM must be active and belong to the item type.');
    END IF;

    IF INSERTING THEN
        :NEW.created_by := NVL(:NEW.created_by, l_user);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1);
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1;
    END IF;
    :NEW.last_updated_by := l_user;
    :NEW.last_update_date := SYSDATE;
    :NEW.last_update_login := l_login;
END;
