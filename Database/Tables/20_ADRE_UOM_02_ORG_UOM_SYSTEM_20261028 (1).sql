CREATE TABLE ops.adre_inv_item_org_uom_system
(
    org_uom_system_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ebs_organization_id NUMBER NOT NULL,
    measurement_system VARCHAR2(10) NOT NULL,
    active_flag         VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by          VARCHAR2(100) NOT NULL,
    creation_date       DATE DEFAULT SYSDATE NOT NULL,
    last_updated_by     VARCHAR2(100) NOT NULL,
    last_update_date    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT adre_inv_org_uom_sys_pk PRIMARY KEY (org_uom_system_id),
    CONSTRAINT adre_inv_org_uom_sys_u1 UNIQUE (ebs_organization_id),
    CONSTRAINT adre_inv_org_uom_sys_ck1 CHECK (measurement_system IN ('IMPERIAL', 'METRIC')),
    CONSTRAINT adre_inv_org_uom_sys_ck2 CHECK (active_flag IN ('Y', 'N'))
);

-- Maintain creation and last-update metadata on this configuration table.
CREATE OR REPLACE TRIGGER ops.adre_inv_org_uom_sys_biu
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_org_uom_system
FOR EACH ROW
DECLARE
    l_actor VARCHAR2(100);
BEGIN
    l_actor := SUBSTR
    (
        NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'),
            SYS_CONTEXT('USERENV', 'SESSION_USER')),
        1,
        100
    );

    IF INSERTING THEN
        :NEW.created_by    := NVL(:NEW.created_by, l_actor);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
    ELSE
        :NEW.created_by    := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
    END IF;

    :NEW.last_updated_by  := l_actor;
    :NEW.last_update_date := SYSDATE;
END;
/
