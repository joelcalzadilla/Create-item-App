-- Adhesives Research
-- Script  : 26_adre_inv_item_pri_uom_rule.sql
-- Purpose : Configure EBS primary UOM resolution by item type, organization and UOM class.
-- Order   : 26. Run once after Tables/25.
-- Requires: OPS.ADRE_INV_ITEM_TYPE. Load configuration and grant APPS SELECT separately.
-- No existing tables or rows are replaced.

CREATE TABLE ops.adre_inv_item_pri_uom_rule
(
    rule_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    item_type_id          NUMBER NOT NULL,
    ebs_organization_id   NUMBER NOT NULL,
    uom_class             VARCHAR2(30) NOT NULL,
    resolution_method     VARCHAR2(10) NOT NULL,
    target_uom_code       VARCHAR2(30),
    active_flag           VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by            VARCHAR2(100) NOT NULL,
    creation_date         DATE DEFAULT SYSDATE NOT NULL,
    last_updated_by       VARCHAR2(100) NOT NULL,
    last_update_date      DATE DEFAULT SYSDATE NOT NULL,
    last_update_login     VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT adre_pri_uom_rule_pk PRIMARY KEY (rule_id),
    CONSTRAINT adre_pri_uom_rule_c1 CHECK (ebs_organization_id > 0),
    CONSTRAINT adre_pri_uom_rule_c2 CHECK (active_flag IN ('Y', 'N')),
    CONSTRAINT adre_pri_uom_rule_c3 CHECK (record_version_number > 0),
    CONSTRAINT adre_pri_uom_rule_c4 CHECK
    (
        (resolution_method = 'KEEP' AND target_uom_code IS NULL)
        OR (resolution_method = 'FIXED' AND target_uom_code IS NOT NULL)
    ),
    CONSTRAINT adre_pri_uom_rule_f1 FOREIGN KEY (item_type_id)
        REFERENCES ops.adre_inv_item_type (item_type_id)
);

CREATE UNIQUE INDEX ops.adre_pri_uom_rule_u1
    ON ops.adre_inv_item_pri_uom_rule
       (item_type_id, ebs_organization_id, uom_class);

CREATE INDEX ops.adre_pri_uom_rule_n1
    ON ops.adre_inv_item_pri_uom_rule
       (ebs_organization_id, active_flag);

COMMENT ON TABLE ops.adre_inv_item_pri_uom_rule IS
    'Resolves the EBS primary UOM by item type, inventory organization and EBS UOM class. KEEP retains the staged UOM; FIXED chooses the configured destination.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.rule_id IS
    'Surrogate identifier of the primary UOM rule.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.item_type_id IS
    'Application item type; references OPS.ADRE_INV_ITEM_TYPE.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.ebs_organization_id IS
    'Existing EBS inventory organization validated against MTL_PARAMETERS by the package.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.uom_class IS
    'EBS UOM class of the UOM selected in the organization request, for example LENGTH or QUANTITY.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.resolution_method IS
    'KEEP retains the organization request UOM; FIXED uses TARGET_UOM_CODE.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.target_uom_code IS
    'Destination EBS primary UOM for FIXED rules; NULL for KEEP rules.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.active_flag IS
    'Y makes the rule available for new EBS submissions.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.created_by IS
    'Creator identity resolved from APEX APP_USER or database user, preserved on update.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.creation_date IS
    'Creation date and time, preserved on update.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.last_updated_by IS
    'Identity responsible for the latest insert or update.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.last_update_date IS
    'Database date and time of the latest insert or update.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.last_update_login IS
    'APEX APP_SESSION for the latest insert or update; database user outside APEX.';
COMMENT ON COLUMN ops.adre_inv_item_pri_uom_rule.record_version_number IS
    'Incremented on update; optimistic locking requires a caller to compare its previously read version.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.trg_adre_pri_uom_rule
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_pri_uom_rule
FOR EACH ROW
DECLARE
    l_user  VARCHAR2(100);
    l_login VARCHAR2(100);
BEGIN
    l_user := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    l_login := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER);

    :NEW.uom_class := UPPER(TRIM(:NEW.uom_class));
    :NEW.resolution_method := UPPER(TRIM(:NEW.resolution_method));
    :NEW.target_uom_code := UPPER(TRIM(:NEW.target_uom_code));
    :NEW.active_flag := UPPER(TRIM(:NEW.active_flag));

    IF INSERTING THEN
        :NEW.created_by := NVL(:NEW.created_by, l_user);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1);
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1;
    END IF;

    :NEW.last_updated_by := l_user;
    :NEW.last_update_date := SYSDATE;
    :NEW.last_update_login := l_login;
END;
