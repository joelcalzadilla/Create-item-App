  CREATE OR REPLACE EDITIONABLE TRIGGER "ADRE_INV_ITEM_CATEGORY_BIU" 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_category
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN
    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );
    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );
    :NEW.category_value :=
        TRIM
        (
            :NEW.category_value
        );
    :NEW.assignment_status :=
        UPPER
        (
            TRIM
            (
                :NEW.assignment_status
            )
        );
    :NEW.api_return_status :=
        UPPER
        (
            TRIM
            (
                :NEW.api_return_status
            )
        );
    IF INSERTING THEN
        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );
        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE
        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;
        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;
    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/
ALTER TRIGGER "ADRE_INV_ITEM_CATEGORY_BIU" ENABLE;