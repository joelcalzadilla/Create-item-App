-- Adhesives Research
-- Script  : 24_adre_inv_item_user_org.sql
-- Purpose : Configure user organization and preferred UOM system without changing existing requests.
-- Order   : 24. Run once after Tables/23.
-- Requires: OPS schema; existing Oracle EBS organizations in APPS.MTL_PARAMETERS.
-- The fallback GRI row and individual user mappings are loaded by the separate seed.

CREATE TABLE ops.adre_inv_item_user_org
(
    user_org_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    app_user_name         VARCHAR2(100),
    ebs_organization_id   NUMBER NOT NULL,
    default_flag          VARCHAR2(1) DEFAULT 'N' NOT NULL,
    preferred_uom_system  VARCHAR2(20),
    active_flag           VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by            VARCHAR2(100) NOT NULL,
    creation_date         DATE DEFAULT SYSDATE NOT NULL,
    last_updated_by       VARCHAR2(100) NOT NULL,
    last_update_date      DATE DEFAULT SYSDATE NOT NULL,
    last_update_login     VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT adre_inv_item_user_org_pk PRIMARY KEY (user_org_id),
    CONSTRAINT adre_inv_item_user_org_c1 CHECK (ebs_organization_id > 0),
    CONSTRAINT adre_inv_item_user_org_c2 CHECK (default_flag IN ('Y', 'N')),
    CONSTRAINT adre_inv_item_user_org_c3 CHECK (active_flag IN ('Y', 'N')),
    CONSTRAINT adre_inv_item_user_org_c4 CHECK (record_version_number > 0),
    CONSTRAINT adre_inv_item_user_org_c5 CHECK
    (
        app_user_name IS NOT NULL OR default_flag = 'Y'
    ),
    CONSTRAINT adre_inv_item_user_org_c6 CHECK
    (
        (default_flag = 'Y'
         AND preferred_uom_system IS NOT NULL
         AND preferred_uom_system IN ('IMPERIAL', 'METRIC'))
        OR
        (default_flag = 'N' AND preferred_uom_system IS NULL)
    )
);

-- A NULL APP_USER_NAME denotes the configured fallback organization.
-- One user may have multiple organizations but only one active default.
CREATE UNIQUE INDEX ops.adre_inv_item_user_org_u1
    ON ops.adre_inv_item_user_org
    (
        UPPER(TRIM(app_user_name)),
        ebs_organization_id
    );

CREATE UNIQUE INDEX ops.adre_inv_item_user_org_u2
    ON ops.adre_inv_item_user_org
    (
        CASE
            WHEN app_user_name IS NOT NULL
             AND active_flag = 'Y'
             AND default_flag = 'Y'
            THEN UPPER(TRIM(app_user_name))
        END
    );

CREATE UNIQUE INDEX ops.adre_inv_item_user_org_u3
    ON ops.adre_inv_item_user_org
    (
        CASE
            WHEN app_user_name IS NULL
             AND active_flag = 'Y'
            THEN 1
        END
    );

CREATE INDEX ops.adre_inv_item_user_org_n1
    ON ops.adre_inv_item_user_org (ebs_organization_id, active_flag);

COMMENT ON TABLE ops.adre_inv_item_user_org IS
    'Maps an APEX user to available EBS organizations. The active default row supplies a preferred UOM system; a NULL user name supplies the global fallback.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.user_org_id IS
    'Surrogate identifier for the user and organization mapping.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.app_user_name IS
    'APEX APP_USER, normalized to uppercase; NULL identifies the global fallback row.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.ebs_organization_id IS
    'Existing Oracle EBS inventory organization, validated by the package against MTL_PARAMETERS.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.default_flag IS
    'Y for the user default or the fallback row; at most one active default per user.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.preferred_uom_system IS
    'IMPERIAL or METRIC preference on the default row; item-type configuration resolves this preference to a specific UOM code.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.active_flag IS
    'Y makes the mapping available for new requests.';
COMMENT ON COLUMN ops.adre_inv_item_user_org.record_version_number IS
    'Incremented on update; callers must compare their previously read value for optimistic locking.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.trg_adre_inv_item_user_org
BEFORE INSERT OR UPDATE ON ops.adre_inv_item_user_org
FOR EACH ROW
DECLARE
    l_user  VARCHAR2(100);
    l_login VARCHAR2(100);
BEGIN
    l_user := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER);
    l_login := NVL(SYS_CONTEXT('APEX$SESSION', 'APP_SESSION'), USER);

    :NEW.app_user_name := UPPER(TRIM(:NEW.app_user_name));
    :NEW.default_flag := UPPER(TRIM(:NEW.default_flag));
    :NEW.preferred_uom_system := UPPER(TRIM(:NEW.preferred_uom_system));
    :NEW.active_flag := UPPER(TRIM(:NEW.active_flag));

    IF INSERTING THEN
        :NEW.created_by := NVL(:NEW.created_by, l_user);
        :NEW.creation_date := NVL(:NEW.creation_date, SYSDATE);
        :NEW.record_version_number := NVL(:NEW.record_version_number, 1);
    ELSE
        :NEW.created_by := :OLD.created_by;
        :NEW.creation_date := :OLD.creation_date;
        :NEW.record_version_number := NVL(:OLD.record_version_number, 0) + 1;
    END IF;

    :NEW.last_updated_by := l_user;
    :NEW.last_update_date := SYSDATE;
    :NEW.last_update_login := l_login;
END;
/

