CREATE TABLE ops.adre_inv_item_bom
(
    item_bom_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
    request_org_id NUMBER NOT NULL ENABLE,
    alternate_bom_designator VARCHAR2(30),
    bom_description VARCHAR2(500),
    effectivity_date DATE,
    ebs_bill_sequence_id NUMBER,
    bom_status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL ENABLE,
    api_return_status VARCHAR2(10),
    api_message_count NUMBER,
    api_message_text CLOB,
    api_processed_date DATE,
    created_by VARCHAR2(100) NOT NULL ENABLE,
    creation_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_updated_by VARCHAR2(100) NOT NULL ENABLE,
    last_update_date DATE DEFAULT SYSDATE NOT NULL ENABLE,
    last_update_login VARCHAR2(100),
    record_version_number NUMBER DEFAULT 1 NOT NULL ENABLE,
    CONSTRAINT adre_inv_item_bom_ck1 CHECK ( bom_status IN ( 'DRAFT', 'READY', 'PROCESSING', 'PROCESSED', 'ERROR', 'SKIPPED' ) ) ENABLE,
    CONSTRAINT adre_inv_item_bom_ck2 CHECK ( ebs_bill_sequence_id IS NULL OR ebs_bill_sequence_id > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_bom_ck3 CHECK ( api_message_count IS NULL OR api_message_count >= 0 ) ENABLE,
    CONSTRAINT adre_inv_item_bom_ck4 CHECK ( record_version_number > 0 ) ENABLE,
    CONSTRAINT adre_inv_item_bom_pk PRIMARY KEY (item_bom_id) USING INDEX ENABLE
);

ALTER TABLE ops.adre_inv_item_bom ADD CONSTRAINT adre_inv_item_bom_fk1 FOREIGN KEY (request_org_id)
	  REFERENCES ops.adre_inv_item_request_org (request_org_id) ENABLE;

CREATE INDEX ops.adre_inv_item_bom_n1 ON ops.adre_inv_item_bom (request_org_id, bom_status) 
  ;

CREATE INDEX ops.adre_inv_item_bom_n2 ON ops.adre_inv_item_bom (bom_status, request_org_id) 
  ;

CREATE INDEX ops.adre_inv_item_bom_n3 ON ops.adre_inv_item_bom (ebs_bill_sequence_id) 
  ;

COMMENT ON COLUMN ops.adre_inv_item_bom.item_bom_id IS 'Surrogate primary key generated by Oracle for each Bill of Material header.';

COMMENT ON COLUMN ops.adre_inv_item_bom.request_org_id IS 'Foreign key identifying the Item Request organization to which the Bill of Material applies.';

COMMENT ON COLUMN ops.adre_inv_item_bom.alternate_bom_designator IS 'Optional Oracle EBS alternate BOM designator. NULL represents the Primary BOM.';

COMMENT ON COLUMN ops.adre_inv_item_bom.bom_description IS 'Business description of the Bill of Material.';

COMMENT ON COLUMN ops.adre_inv_item_bom.effectivity_date IS 'Date from which the Bill of Material becomes effective.';

COMMENT ON COLUMN ops.adre_inv_item_bom.ebs_bill_sequence_id IS 'Oracle EBS Bill Sequence identifier returned or resolved after BOM processing.';

COMMENT ON COLUMN ops.adre_inv_item_bom.bom_status IS 'Current processing status of the BOM header. Valid values are DRAFT, READY, PROCESSING, PROCESSED, ERROR and SKIPPED.';

COMMENT ON COLUMN ops.adre_inv_item_bom.api_return_status IS 'Return status received from the Oracle EBS BOM API.';

COMMENT ON COLUMN ops.adre_inv_item_bom.api_message_count IS 'Number of messages returned by the Oracle EBS BOM API.';

COMMENT ON COLUMN ops.adre_inv_item_bom.api_message_text IS 'Message or error information returned by the Oracle EBS BOM API.';

COMMENT ON COLUMN ops.adre_inv_item_bom.api_processed_date IS 'Date and time when Oracle EBS API processing completed for the BOM header.';

COMMENT ON TABLE ops.adre_inv_item_bom  IS 'Transaction table containing Bill of Material headers associated with each Item Request organization in the Adhesives Research Inventory Item Creation application.';

COMMENT ON COLUMN ops.adre_inv_item_bom.created_by IS 'Creator identity supplied on insert or resolved from APEX APP_USER, falling back to the database user. Preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_bom.creation_date IS 'Creation date and time, initialized on insert and preserved on update.';

COMMENT ON COLUMN ops.adre_inv_item_bom.last_updated_by IS 'User responsible for the latest insert or update, resolved from APEX APP_USER or the database user.';

COMMENT ON COLUMN ops.adre_inv_item_bom.last_update_date IS 'Database date and time of the latest insert or update, maintained by the audit trigger.';

COMMENT ON COLUMN ops.adre_inv_item_bom.last_update_login IS 'APEX APP_SESSION identifier for the latest insert or update; database user is used outside APEX.';

COMMENT ON COLUMN ops.adre_inv_item_bom.record_version_number IS 'Positive row version initialized on insert and incremented on each update. Optimistic locking requires the application to compare its previously read version with the stored version.';

CREATE OR REPLACE EDITIONABLE TRIGGER ops.adre_inv_item_bom_biu 
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_bom
FOR EACH ROW
DECLARE
    l_user
        VARCHAR2(100);
    l_login
        VARCHAR2(100);
BEGIN

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );

    :NEW.alternate_bom_designator :=
        UPPER
        (
            TRIM
            (
                :NEW.alternate_bom_designator
            )
        );

    :NEW.bom_description :=
        TRIM
        (
            :NEW.bom_description
        );

    :NEW.bom_status :=
        UPPER
        (
            TRIM
            (
                :NEW.bom_status
            )
        );

    :NEW.api_return_status :=
        UPPER
        (
            TRIM
            (
                :NEW.api_return_status
            )
        );
    IF INSERTING THEN

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );
        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );

        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );
    ELSE

        :NEW.created_by :=
            :OLD.created_by;
        :NEW.creation_date :=
            :OLD.creation_date;

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;
    END IF;

    :NEW.last_updated_by :=
        l_user;
    :NEW.last_update_date :=
        SYSDATE;
    :NEW.last_update_login :=
        l_login;
END;

/

ALTER TRIGGER ops.adre_inv_item_bom_biu ENABLE;
