-- Purpose:
-- Recreate the Item Document transaction table for the final
-- Adhesives Research Inventory Item Creation application.
--
-- This table stores documents and file attachments associated with an
-- Item Request organization.
--
-- One row represents one document attachment.
--
-- REQUEST_ORG_ID identifies the Item Request organization to which the
-- document belongs.
--
-- FILE_BLOB stores the actual binary file content.
--
-- FILE_NAME, MIME_TYPE and FILE_CHARSET store the file metadata used by
-- Oracle APEX for upload and download operations.
--
-- Documents can remain in DRAFT status while the Item Request is being
-- prepared.
-- =====================================================================


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Drop the existing table when it already exists.
--
-- CASCADE CONSTRAINTS removes foreign key references from previously
-- created dependent application objects during the schema rebuild.
--
-- ORA-00942 is ignored because it means the table does not exist.
-- Any other Oracle error is raised normally.
-- =====================================================================

BEGIN
    EXECUTE IMMEDIATE
        'DROP TABLE ops.adre_inv_item_document CASCADE CONSTRAINTS PURGE';

EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Item Document transaction table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_document
(
    item_document_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    request_org_id
        NUMBER
        NOT NULL,

    document_type
        VARCHAR2(100),

    document_title
        VARCHAR2(240)
        NOT NULL,

    document_description
        VARCHAR2(2000),

    file_name
        VARCHAR2(500),

    mime_type
        VARCHAR2(255),

    file_charset
        VARCHAR2(100),

    file_blob
        BLOB,

    document_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    api_return_status
        VARCHAR2(10),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_document_pk
        PRIMARY KEY
        (
            item_document_id
        ),

    CONSTRAINT adre_inv_item_document_fk1
        FOREIGN KEY
        (
            request_org_id
        )
        REFERENCES ops.adre_inv_item_request_org
        (
            request_org_id
        ),

    CONSTRAINT adre_inv_item_document_ck1
        CHECK
        (
            document_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR',
                'SKIPPED'
            )
        ),

    CONSTRAINT adre_inv_item_document_ck2
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),

    CONSTRAINT adre_inv_item_document_ck3
        CHECK
        (
            record_version_number > 0
        )
);


