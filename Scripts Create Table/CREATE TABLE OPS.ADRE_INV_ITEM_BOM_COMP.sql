-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Bill of Material component transaction table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_bom_comp
(
    item_bom_comp_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    item_bom_id
        NUMBER
        NOT NULL,

    component_item_number
        VARCHAR2(250)
        NOT NULL,

    ebs_component_item_id
        NUMBER,

    component_quantity
        NUMBER
        NOT NULL,

    component_uom_code
        VARCHAR2(30),

    operation_sequence
        NUMBER
        DEFAULT 1
        NOT NULL,

    item_sequence
        NUMBER,

    effectivity_date
        DATE,

    disable_date
        DATE,

    supply_type
        VARCHAR2(30),

    component_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    api_return_status
        VARCHAR2(10),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_bom_comp_pk
        PRIMARY KEY
        (
            item_bom_comp_id
        ),

    CONSTRAINT adre_inv_item_bom_comp_fk1
        FOREIGN KEY
        (
            item_bom_id
        )
        REFERENCES ops.adre_inv_item_bom
        (
            item_bom_id
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck1
        CHECK
        (
            component_quantity > 0
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck2
        CHECK
        (
            operation_sequence > 0
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck3
        CHECK
        (
            item_sequence IS NULL
            OR item_sequence > 0
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck4
        CHECK
        (
            disable_date IS NULL
            OR effectivity_date IS NULL
            OR disable_date >= effectivity_date
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck5
        CHECK
        (
            component_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR',
                'SKIPPED'
            )
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck6
        CHECK
        (
            ebs_component_item_id IS NULL
            OR ebs_component_item_id > 0
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck7
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),

    CONSTRAINT adre_inv_item_bom_comp_ck8
        CHECK
        (
            record_version_number > 0
        )
);


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Prevent duplicate component definitions for the same BOM using the
-- component item number, operation sequence and item sequence.
--
-- A NULL ITEM_SEQUENCE is normalized to -1 only for uniqueness
-- evaluation.
-- =====================================================================

CREATE UNIQUE INDEX ops.adre_inv_item_bom_comp_u1
    ON ops.adre_inv_item_bom_comp
    (
        item_bom_id,

        UPPER
        (
            TRIM
            (
                component_item_number
            )
        ),

        operation_sequence,

        NVL
        (
            item_sequence,
            -1
        )
    );


