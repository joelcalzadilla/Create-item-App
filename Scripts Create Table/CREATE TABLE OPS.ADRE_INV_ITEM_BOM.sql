-- Purpose:
-- Recreate the Bill of Material header transaction table for the final
-- Adhesives Research Inventory Item Creation application.
--
-- One row represents one BOM header associated with one Item Request
-- organization.
--
-- REQUEST_ORG_ID identifies the organization where the BOM applies.
--
-- ALTERNATE_BOM_DESIGNATOR is optional.
-- A NULL value represents the Primary BOM.
--
-- EBS_BILL_SEQUENCE_ID stores the Oracle EBS Bill Sequence identifier
-- after the BOM has been created or resolved in Oracle EBS.
--
-- BOM components will be stored separately in
-- ADRE_INV_ITEM_BOM_COMP.
-- =====================================================================


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Drop the existing table when it already exists.
--
-- CASCADE CONSTRAINTS removes foreign key references from previously
-- created dependent application objects during the schema rebuild.
--
-- ORA-00942 is ignored because it means the table does not exist.
-- Any other Oracle error is raised normally.
-- =====================================================================

BEGIN
    EXECUTE IMMEDIATE
        'DROP TABLE ops.adre_inv_item_bom CASCADE CONSTRAINTS PURGE';

EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Bill of Material header transaction table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_bom
(
    item_bom_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    request_org_id
        NUMBER
        NOT NULL,

    alternate_bom_designator
        VARCHAR2(30),

    bom_description
        VARCHAR2(500),

    effectivity_date
        DATE,

    ebs_bill_sequence_id
        NUMBER,

    bom_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    api_return_status
        VARCHAR2(10),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_bom_pk
        PRIMARY KEY
        (
            item_bom_id
        ),

    CONSTRAINT adre_inv_item_bom_fk1
        FOREIGN KEY
        (
            request_org_id
        )
        REFERENCES ops.adre_inv_item_request_org
        (
            request_org_id
        ),

    CONSTRAINT adre_inv_item_bom_ck1
        CHECK
        (
            bom_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR',
                'SKIPPED'
            )
        ),

    CONSTRAINT adre_inv_item_bom_ck2
        CHECK
        (
            ebs_bill_sequence_id IS NULL
            OR ebs_bill_sequence_id > 0
        ),

    CONSTRAINT adre_inv_item_bom_ck3
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),

    CONSTRAINT adre_inv_item_bom_ck4
        CHECK
        (
            record_version_number > 0
        )
);


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Prevent duplicate BOM headers for the same Item Request organization.
--
-- A NULL ALTERNATE_BOM_DESIGNATOR represents the Primary BOM.
--
-- NVL is used so only one Primary BOM can exist for a REQUEST_ORG_ID.
--
-- Multiple alternate BOMs are allowed as long as each alternate
-- designator is unique for the Item Request organization.
-- =====================================================================

CREATE UNIQUE INDEX ops.adre_inv_item_bom_u1
    ON ops.adre_inv_item_bom
    (
        request_org_id,

        NVL
        (
            UPPER
            (
                TRIM
                (
                    alternate_bom_designator
                )
            ),
            '~PRIMARY~'
        )
    );


