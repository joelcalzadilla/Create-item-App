-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Oracle EBS Item Template configuration table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_template
(
    item_template_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    ebs_template_id
        NUMBER,

    template_name
        VARCHAR2(240)
        NOT NULL,

    description
        VARCHAR2(1000),

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_template_pk
        PRIMARY KEY
        (
            item_template_id
        ),

    CONSTRAINT adre_inv_item_template_u1
        UNIQUE
        (
            template_name
        ),

    CONSTRAINT adre_inv_item_template_u2
        UNIQUE
        (
            ebs_template_id
        ),

    CONSTRAINT adre_inv_item_template_ck1
        CHECK
        (
            active_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_template_ck2
        CHECK
        (
            ebs_template_id IS NULL
            OR ebs_template_id > 0
        ),

    CONSTRAINT adre_inv_item_template_ck3
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_template_ck4
        CHECK
        (
            record_version_number > 0
        )
);


