-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the final Item Category table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_category
(
    item_category_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    request_org_id
        NUMBER
        NOT NULL,

    ebs_category_set_id
        NUMBER
        NOT NULL,

    ebs_category_id
        NUMBER,

    category_value
        VARCHAR2(500),

    assignment_status
        VARCHAR2(30)
        DEFAULT 'DRAFT'
        NOT NULL,

    api_return_status
        VARCHAR2(30),

    api_message_count
        NUMBER,

    api_message_text
        CLOB,

    api_processed_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,


    CONSTRAINT adre_inv_item_category_pk
        PRIMARY KEY
        (
            item_category_id
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- REQUEST_ORG remains application-owned and therefore retains its
    -- local foreign key.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_fk1
        FOREIGN KEY
        (
            request_org_id
        )
        REFERENCES ops.adre_inv_item_request_org
        (
            request_org_id
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Prevent the same Oracle EBS Category Set from being assigned
    -- more than once to the same Request Organization.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_u1
        UNIQUE
        (
            request_org_id,
            ebs_category_set_id
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Require a valid positive Oracle EBS Category Set identifier.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_ck1
        CHECK
        (
            ebs_category_set_id > 0
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- EBS_CATEGORY_ID may remain NULL while Draft, but must be
    -- positive when populated.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_ck2
        CHECK
        (
            ebs_category_id IS NULL
            OR ebs_category_id > 0
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Restrict Category processing status to supported application
    -- values.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_ck3
        CHECK
        (
            assignment_status IN
            (
                'DRAFT',
                'READY',
                'PROCESSING',
                'PROCESSED',
                'ERROR',
                'SKIPPED'
            )
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- API message count cannot be negative.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_ck4
        CHECK
        (
            api_message_count IS NULL
            OR api_message_count >= 0
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- Record version must always be positive.
    -- =================================================================

    CONSTRAINT adre_inv_item_category_ck5
        CHECK
        (
            record_version_number > 0
        )
);


