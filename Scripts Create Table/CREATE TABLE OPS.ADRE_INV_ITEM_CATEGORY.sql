-- Validate the direct Oracle EBS Category references.
--
-- Expected:
--
-- EBS_CATEGORY_SET_ID    NUMBER   NULLABLE = N
-- EBS_CATEGORY_ID        NUMBER   NULLABLE = Y
-- =====================================================================

SELECT
    column_name,
    data_type,
    nullable
FROM all_tab_columns
WHERE owner = 'OPS'
  AND table_name = 'ADRE_INV_ITEM_CATEGORY'
  AND column_name IN
      (
          'EBS_CATEGORY_SET_ID',
          'EBS_CATEGORY_ID'
      )
ORDER BY column_id;


-- =====================================================================
-- JCALZADILLA - 22.08.2026
