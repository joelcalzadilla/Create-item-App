    column_name
FROM all_tab_columns
WHERE owner = 'OPS'
  AND table_name = 'ADRE_INV_ITEM_CATEGORY'
  AND column_name = 'ITEM_CAT_SET_ID';


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Validate foreign keys.
--
-- Expected:
--
-- REQUEST_ORG_ID -> ADRE_INV_ITEM_REQUEST_ORG
--
-- There must be no foreign key to Oracle EBS base tables.
-- =====================================================================

SELECT
    c.constraint_name,
    cc.column_name,
    r.table_name AS referenced_table
FROM all_constraints c
JOIN all_cons_columns cc
  ON cc.owner = c.owner
 AND cc.constraint_name = c.constraint_name
JOIN all_constraints r
  ON r.owner = c.r_owner
 AND r.constraint_name = c.r_constraint_name
WHERE c.owner = 'OPS'
  AND c.table_name = 'ADRE_INV_ITEM_CATEGORY'
  AND c.constraint_type = 'R'
ORDER BY
    c.constraint_name,
    cc.position;


