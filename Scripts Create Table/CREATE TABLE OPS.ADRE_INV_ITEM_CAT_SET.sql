-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Create the Oracle EBS Category Set configuration table.
-- =====================================================================

CREATE TABLE ops.adre_inv_item_cat_set
(
    item_cat_set_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    ebs_category_set_id
        NUMBER
        NOT NULL,

    category_set_name
        VARCHAR2(240)
        NOT NULL,

    control_level
        NUMBER
        NOT NULL,

    required_flag
        VARCHAR2(1)
        DEFAULT 'N'
        NOT NULL,

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_cat_set_pk
        PRIMARY KEY
        (
            item_cat_set_id
        ),

    CONSTRAINT adre_inv_item_cat_set_u1
        UNIQUE
        (
            ebs_category_set_id
        ),

    CONSTRAINT adre_inv_item_cat_set_u2
        UNIQUE
        (
            category_set_name
        ),

    CONSTRAINT adre_inv_item_cat_set_ck1
        CHECK
        (
            control_level IN
            (
                1,
                2
            )
        ),

    CONSTRAINT adre_inv_item_cat_set_ck2
        CHECK
        (
            required_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_cat_set_ck3
        CHECK
        (
            active_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_cat_set_ck4
        CHECK
        (
            ebs_category_set_id > 0
        ),

    CONSTRAINT adre_inv_item_cat_set_ck5
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_cat_set_ck6
        CHECK
        (
            record_version_number > 0
        )
);


