-- CONTROL_LEVEL determines where the category is controlled:
--
--   1 = Item / Master Organization controlled
--   2 = Organization controlled
--
-- REQUIRED_FLAG determines whether a category value must be populated
-- before the Item Request can be sent to Oracle EBS.
--
-- The application uses this configuration instead of hardcoding
-- Category Set identifiers or names in Oracle APEX or PL/SQL.
-- =====================================================================


-- =====================================================================
-- JCALZADILLA - 22.08.2026
-- Drop the existing table when it already exists.
--
-- CASCADE CONSTRAINTS removes foreign key references from previously
-- created dependent application objects during the schema rebuild.
--
-- ORA-00942 is ignored because it means the table does not exist.
-- Any other Oracle error is raised normally.
-- =====================================================================

BEGIN
    EXECUTE IMMEDIATE
        'DROP TABLE ops.adre_inv_item_cat_set CASCADE CONSTRAINTS PURGE';

EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
