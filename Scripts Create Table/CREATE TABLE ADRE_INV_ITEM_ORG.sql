-- =====================================================================

CREATE TABLE ops.adre_inv_item_org
(
    item_org_id
        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    organization_id
        NUMBER
        NOT NULL,

    organization_code
        VARCHAR2(30)
        NOT NULL,

    organization_name
        VARCHAR2(240)
        NOT NULL,

    default_role
        VARCHAR2(30)
        NOT NULL,

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    display_sequence
        NUMBER
        DEFAULT 10
        NOT NULL,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,

    CONSTRAINT adre_inv_item_org_pk
        PRIMARY KEY
        (
            item_org_id
        ),

    CONSTRAINT adre_inv_item_org_u1
        UNIQUE
        (
            organization_id
        ),

    CONSTRAINT adre_inv_item_org_u2
        UNIQUE
        (
            organization_code
        ),

    CONSTRAINT adre_inv_item_org_ck1
        CHECK
        (
            default_role IN
            (
                'MASTER',
                'TARGET'
            )
        ),

    CONSTRAINT adre_inv_item_org_ck2
        CHECK
        (
            active_flag IN
            (
                'Y',
                'N'
            )
        ),

    CONSTRAINT adre_inv_item_org_ck3
        CHECK
        (
            organization_id > 0
        ),

    CONSTRAINT adre_inv_item_org_ck4
        CHECK
        (
            display_sequence > 0
        ),

    CONSTRAINT adre_inv_item_org_ck5
        CHECK
        (
            record_version_number > 0
        )
);


