-- =====================================================================
-- JCALZADILLA - 22.08.2026 - START CHANGE
-- Purpose:
-- Automatically maintain audit information and normalize Item Template
-- Rule configuration values.
-- =====================================================================

CREATE OR REPLACE TRIGGER ops.adre_inv_item_tmpl_rule_biu
BEFORE INSERT OR UPDATE
ON ops.adre_inv_item_template_rule
FOR EACH ROW

DECLARE

    l_user
        VARCHAR2(100);

    l_login
        VARCHAR2(100);

BEGIN

    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX user when available.

    l_user :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_USER'
            ),
            USER
        );


    -- JCALZADILLA - 22.08.2026
    -- Resolve the Oracle APEX session identifier when available.

    l_login :=
        NVL
        (
            SYS_CONTEXT
            (
                'APEX$SESSION',
                'APP_SESSION'
            ),
            USER
        );


    -- JCALZADILLA - 22.08.2026
    -- Normalize optional rule criteria.

    :NEW.division_value :=
        TRIM
        (
            :NEW.division_value
        );


    :NEW.business_unit_value :=
        TRIM
        (
            :NEW.business_unit_value
        );


    :NEW.expense_item_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.expense_item_flag
            )
        );


    -- JCALZADILLA - 22.08.2026
    -- Normalize rule status and active indicator.

    :NEW.rule_status :=
        UPPER
        (
            TRIM
            (
                :NEW.rule_status
            )
        );


    :NEW.active_flag :=
        UPPER
        (
            TRIM
            (
                :NEW.active_flag
            )
        );


    -- JCALZADILLA - 22.08.2026
    -- Remove unnecessary surrounding spaces from rule notes.

    :NEW.rule_notes :=
        TRIM
        (
            :NEW.rule_notes
        );


    IF INSERTING THEN

        -- JCALZADILLA - 22.08.2026
        -- Initialize creation audit information.

        :NEW.created_by :=
            NVL
            (
                :NEW.created_by,
                l_user
            );


        :NEW.creation_date :=
            NVL
            (
                :NEW.creation_date,
                SYSDATE
            );


        :NEW.record_version_number :=
            NVL
            (
                :NEW.record_version_number,
                1
            );

    ELSE

        -- JCALZADILLA - 22.08.2026
        -- Preserve original creation audit information.

        :NEW.created_by :=
            :OLD.created_by;

        :NEW.creation_date :=
            :OLD.creation_date;


        -- JCALZADILLA - 22.08.2026
        -- Increment the row version number.

        :NEW.record_version_number :=
            NVL
            (
                :OLD.record_version_number,
                0
            ) + 1;

    END IF;


    -- JCALZADILLA - 22.08.2026
    -- Refresh last-update audit information.

    :NEW.last_updated_by :=
        l_user;

    :NEW.last_update_date :=
        SYSDATE;

    :NEW.last_update_login :=
        l_login;

END;
/

