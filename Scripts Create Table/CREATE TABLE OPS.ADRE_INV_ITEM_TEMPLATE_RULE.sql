        NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
        NOT NULL,

    item_type_id
        NUMBER
        NOT NULL,

    ebs_organization_id
        NUMBER,

    division_value
        VARCHAR2(240),

    business_unit_value
        VARCHAR2(240),

    expense_item_flag
        VARCHAR2(1),

    ebs_template_id
        NUMBER,

    rule_status
        VARCHAR2(30)
        DEFAULT 'READY'
        NOT NULL,

    rule_notes
        VARCHAR2(2000),

    rule_priority
        NUMBER
        DEFAULT 100
        NOT NULL,

    active_flag
        VARCHAR2(1)
        DEFAULT 'Y'
        NOT NULL,

    effective_start_date
        DATE,

    effective_end_date
        DATE,

    created_by
        VARCHAR2(100)
        NOT NULL,

    creation_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_updated_by
        VARCHAR2(100)
        NOT NULL,

    last_update_date
        DATE
        DEFAULT SYSDATE
        NOT NULL,

    last_update_login
        VARCHAR2(100),

    record_version_number
        NUMBER
        DEFAULT 1
        NOT NULL,


    CONSTRAINT adre_inv_item_template_rule_pk
        PRIMARY KEY
        (
            item_template_rule_id
        ),


    -- =================================================================
    -- JCALZADILLA - 22.08.2026
    -- ITEM_TYPE remains application-owned configuration and therefore
    -- retains its local foreign key.
    -- =================================================================

    CONSTRAINT adre_inv_item_template_rule_fk1
        FOREIGN KEY
        (
            item_type_id
        )
        REFERENCES ops.adre_inv_item_type
        (
            item_type_id
        ),


    CONSTRAINT adre_inv_item_template_rule_ck1
        CHECK
        (
            ebs_organization_id IS NULL
            OR ebs_organization_id > 0
        ),


    CONSTRAINT adre_inv_item_template_rule_ck2
        CHECK
        (
            expense_item_flag IS NULL
            OR expense_item_flag IN ('Y', 'N')
        ),


    CONSTRAINT adre_inv_item_template_rule_ck3
        CHECK
        (
            ebs_template_id IS NULL
            OR ebs_template_id > 0
        ),


    CONSTRAINT adre_inv_item_template_rule_ck4
        CHECK
        (
            rule_status IN
            (
                'READY',
                'UNSUPPORTED',
                'NEEDS_BUSINESS_DECISION',
                'INVALID_COMBINATION',
                'UNDER_INVESTIGATION'
            )
        ),


    CONSTRAINT adre_inv_item_template_rule_ck5
        CHECK
        (
            rule_status <> 'READY'
            OR ebs_template_id IS NOT NULL
        ),


    CONSTRAINT adre_inv_item_template_rule_ck6
        CHECK
        (
            rule_priority > 0
        ),


    CONSTRAINT adre_inv_item_template_rule_ck7
        CHECK
        (
            active_flag IN ('Y', 'N')
        ),


    CONSTRAINT adre_inv_item_template_rule_ck8
        CHECK
        (
            effective_end_date IS NULL
            OR effective_start_date IS NULL
            OR effective_end_date >= effective_start_date
        ),


    CONSTRAINT adre_inv_item_template_rule_ck9
        CHECK
        (
            record_version_number > 0
        )
);


