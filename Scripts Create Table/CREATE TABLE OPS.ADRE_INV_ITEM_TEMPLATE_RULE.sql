-- Purpose:
-- Recreate the Item Template Rule configuration table for the final
-- Adhesives Research Inventory Item Creation application.
--
-- Oracle EBS is the system of record for:
--
--   - Inventory Organizations
--   - Item Templates
--
-- The application does not maintain local copies of those entities.
--
-- EBS_ORGANIZATION_ID references the Oracle EBS Inventory Organization
-- identifier directly.
--
-- EBS_TEMPLATE_ID references an existing Oracle EBS Item Template
-- identifier directly.
--
-- No foreign key is created from these columns to APPS objects in order
-- to avoid coupling the application schema to Oracle EBS base tables.
--
-- Supported RULE_STATUS values:
--
--   READY
--   UNSUPPORTED
--   NEEDS_BUSINESS_DECISION
--   INVALID_COMBINATION
--   UNDER_INVESTIGATION
--
-- UNSUPPORTED replaces the previous NEEDS_NEW_TEMPLATE status because
-- creation of new Oracle EBS Item Templates is outside the scope of
-- this application.
--
-- A READY rule must always contain an EBS_TEMPLATE_ID.
--
-- NULL values in optional rule criteria represent wildcard or
-- not-applicable conditions.
-- =====================================================================


